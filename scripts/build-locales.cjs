const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const codes=['it','zh-CN','ar','vi','ko','id','pcm'],catalog={};
const slots=text=>(text.match(/\{\d+\}/g)||[]).sort().join(',');
for(const [index,line]of fs.readFileSync(path.join(root,'locales-source.txt'),'utf8').split('\n').entries()){
 if(!line.trim())continue;
 const fields=line.split('|');
 if(fields.length!==8||fields.some(s=>!s.trim()))throw Error('Invalid translation row '+(index+1));
 const [key,...values]=fields;
 if(catalog[key])throw Error('Duplicate translation: '+key);
 const translated={};codes.forEach((code,i)=>{
  if(slots(values[i])!==slots(key))throw Error('Placeholder mismatch: '+key+' / '+code);
  translated[code]=values[i];
 });catalog[key]=translated;
}
const aliases={'← Back to IIOU':'Back to IIOU','← All IOUs':'All IOUs','⚔️ Royal missions':'Royal missions','⭐ Council Patronage':'Council Patronage','⭐ Patronage reroll':'Patronage reroll','⭐ Patronage active for this era':'Patronage active for this era'};
for(const [key,source]of Object.entries(aliases))if(catalog[source])catalog[key]=Object.fromEntries(codes.map(code=>[code,key.slice(0,key.indexOf(source))+catalog[source][code]]));
for(const word of ['Created by mistake','Agreement cancelled','Other reason','Duplicate'])catalog[word.toLowerCase()]=catalog[word];
fs.writeFileSync(path.join(root,'locales.js'),'// Generated by scripts/build-locales.cjs; no network translation service.\nwindow.APP_TRANSLATIONS='+JSON.stringify(catalog,null,2)+';\n');
console.log(Object.keys(catalog).length+' UI messages in eight languages (including source English).');
